type ResourceAccessCapabilities struct {
	Version          int      `json:"version"`
	DelegatedActions []string `json:"delegated_actions"`
}

func resourceAccessCapabilities() ResourceAccessCapabilities {
	actions := make([]string, 0, len(delegatedResourceActions))
	for action := range delegatedResourceActions {
		actions = append(actions, action)
	}
	sort.Strings(actions)
	return ResourceAccessCapabilities{Version: 1, DelegatedActions: actions}
}

