import assert from 'node:assert/strict';
import { test } from 'node:test';
import { pathToFileURL } from 'node:url';

const entry = process.env.WUU_PARITY_SESSIONS_ENTRY;
test('independent session metadata owns CRUD and rejects unsupported rewrites', { skip: !entry }, async () => {
  const { createSessionProvider } = await import(pathToFileURL(entry));
  const provider = createSessionProvider('author-session');
  const call = async (method, ...args) => (await provider.invokeService({service: 'session.domain', method, params: {args}, caller: 'acceptance'})).values;
  provider.initialize(); provider.activate();
  const [created] = await call('CreateWithMetadata', 'thread-one', '/synthetic');
  assert.equal(created.title, 'author-session');
  await assert.rejects(call('CreateWithMetadata', 'thread-one', '/synthetic'), /already exists/);
  assert.equal((await call('Find', 'absent'))[1], false);
  await assert.rejects(call('UpdateTitle', 'absent', 'rename'), error => error.code === 'session_not_found');
  await assert.rejects(call('UpdateTitle', 'thread-one', '  '), /title is required/);
  assert.equal((await call('Find', 'thread-one'))[0].title, 'author-session');
  assert.equal((await call('UpdateTitle', 'thread-one', 'New title'))[0].title, 'New title');
  assert.equal((await call('ListForCWD', '/elsewhere', '', 0))[0].length, 0);
  const [listed] = await call('ListForCWD', '/synthetic', '', 0);
  listed[0].title = 'mutated outside';
  assert.equal((await call('Find', 'thread-one'))[0].title, 'New title');
  assert.ok((await call('UpdateArchived', 'thread-one', true))[0].archived_at);
  assert.equal((await call('UpdateArchived', 'thread-one', false))[0].archived_at, undefined);
  await assert.rejects(call('RewriteHistoryRecordsForEngineEdit', 'thread-one', {}), error => error.code === 'method_not_found');
  assert.equal((await call('Delete', 'thread-one'))[0].id, 'thread-one');
  assert.equal((await call('Find', 'thread-one'))[1], false);
  provider.shutdown();
  await assert.rejects(call('List', 0), error => error.code === 'service_unavailable');
});

test('independent history commits batches atomically and forks detached records', { skip: !entry }, async () => {
  const { createSessionProvider } = await import(pathToFileURL(entry));
  const provider = createSessionProvider(); provider.initialize(); provider.activate();
  const call = async (method, ...args) => (await provider.invokeService({service: 'session.domain', method, params: {args}, caller: 'acceptance'})).values;
  await call('CreateWithMetadata', 'source', '/synthetic');
  assert.deepEqual(await call('AppendHistoryRecordsReturningRange', 'source', [{role: 'user', content: 'question'}, {role: 'assistant', content: 'answer'}]), [1, 2]);
  await assert.rejects(call('AppendHistoryRecords', 'source', [{role: 'user', content: 'uncommitted'}, {role: 'assistant', content: 42}]), /history record/);
  const [source] = await call('LoadProviderHistorySnapshot', 'source');
  assert.equal(source.HeadSeq, 2);
  assert.deepEqual(source.Records.map(record => record.seq), [1, 2]);
  await call('CreateInitialized', {id: 'fork', cwd: '/synthetic', forked_from_id: 'source'}, source.Records);
  await call('AppendHistoryRecord', 'source', {role: 'assistant', content: 'later'});
  assert.deepEqual((await call('LoadHistoryRecords', 'fork', true))[0].map(record => record.content), ['question', 'answer']);
  await assert.rejects(call('CreateInitialized', {id: 'invalid', cwd: '/synthetic'}, [{role: 'user', content: 42}]), /history record/);
  assert.equal((await call('Find', 'invalid'))[1], false);
  await call('Delete', 'fork');
  await assert.rejects(call('LoadHistoryRecords', 'fork', true), error => error.code === 'session_not_found');
  provider.shutdown();
});
