import assert from 'node:assert/strict';
import { test } from 'node:test';
import { pathToFileURL } from 'node:url';

const entry = process.env.WUU_PARITY_SESSIONS_ENTRY;
test('independent session metadata owns CRUD and rejects unsupported rewrites', { skip: !entry }, async () => {
  const { createSessionProvider } = await import(pathToFileURL(entry));
  const provider = createSessionProvider('author-session');
  const call = async (method, ...args) => (await provider.invokeService({service: 'session.domain', method, params: {args}, caller: 'acceptance'})).values;
  provider.initialize(); provider.activate();
  const [created] = await call('CreateWithMetadata', 'thread-one', '/synthetic');
  assert.equal(created.title, 'author-session');
  await assert.rejects(call('CreateWithMetadata', 'thread-one', '/synthetic'), /already exists/);
  assert.equal((await call('Find', 'absent'))[1], false);
  await assert.rejects(call('UpdateTitle', 'absent', 'rename'), error => error.code === 'session_not_found');
  await assert.rejects(call('UpdateTitle', 'thread-one', '  '), /title is required/);
  assert.equal((await call('Find', 'thread-one'))[0].title, 'author-session');
  assert.equal((await call('UpdateTitle', 'thread-one', 'New title'))[0].title, 'New title');
  assert.equal((await call('ListForCWD', '/elsewhere', '', 0))[0].length, 0);
  const [listed] = await call('ListForCWD', '/synthetic', '', 0);
  listed[0].title = 'mutated outside';
  assert.equal((await call('Find', 'thread-one'))[0].title, 'New title');
  assert.ok((await call('UpdateArchived', 'thread-one', true))[0].archived_at);
  assert.equal((await call('UpdateArchived', 'thread-one', false))[0].archived_at, undefined);
  await assert.rejects(call('RewriteHistoryRecordsForEngineEdit', 'thread-one', {}), error => error.code === 'method_not_found');
  assert.equal((await call('Delete', 'thread-one'))[0].id, 'thread-one');
  assert.equal((await call('Find', 'thread-one'))[1], false);
  provider.shutdown();
  await assert.rejects(call('List', 0), error => error.code === 'service_unavailable');
});

test('independent history commits batches atomically and forks detached records', { skip: !entry }, async () => {
  const { createSessionProvider } = await import(pathToFileURL(entry));
  const provider = createSessionProvider(); provider.initialize(); provider.activate();
  const call = async (method, ...args) => (await provider.invokeService({service: 'session.domain', method, params: {args}, caller: 'acceptance'})).values;
  await call('CreateWithMetadata', 'source', '/synthetic');
  assert.deepEqual(await call('AppendHistoryRecordsReturningRange', 'source', [{role: 'user', content: 'question'}, {role: 'assistant', content: 'answer'}]), [1, 2]);
  await assert.rejects(call('AppendHistoryRecords', 'source', [{role: 'user', content: 'uncommitted'}, {role: 'assistant', content: 42}]), /history record/);
  const [source] = await call('LoadProviderHistorySnapshot', 'source');
  assert.equal(source.HeadSeq, 2);
  assert.deepEqual(source.Records.map(record => record.seq), [1, 2]);
  await call('CreateInitialized', {id: 'fork', cwd: '/synthetic', forked_from_id: 'source'}, source.Records);
  await call('AppendHistoryRecord', 'source', {role: 'assistant', content: 'later'});
  assert.deepEqual((await call('LoadHistoryRecords', 'fork', true))[0].map(record => record.content), ['question', 'answer']);
  await assert.rejects(call('CreateInitialized', {id: 'invalid', cwd: '/synthetic'}, [{role: 'user', content: 42}]), /history record/);
  assert.equal((await call('Find', 'invalid'))[1], false);
  await call('Delete', 'fork');
  await assert.rejects(call('LoadHistoryRecords', 'fork', true), error => error.code === 'session_not_found');
  provider.shutdown();
});

test('independent journal records transitions, rejects foreign handles and reconciles closed owners', {skip: !entry}, async () => {
  const {createSessionProvider} = await import(pathToFileURL(entry));
  const provider = createSessionProvider(); provider.initialize(); provider.activate();
  const callAs = async (caller, method, ...args) => (await provider.invokeService({service: 'session.domain', method, params: {args}, caller})).values;
  const call = (method, ...args) => callAs('owner', method, ...args);
  const [handle] = await call('NewInferenceJournalRuntime', 'workspace');
  await assert.rejects(callAs('foreign', 'Journal.Prune', handle.handle, '2026-01-01T00:00:00Z'), error => error.code === 'resource_unavailable');
  const operation = {At: '2026-01-01T00:00:00Z', RequestHash: 'request', Workflow: {ID: 'workflow', StartedAt: '2026-01-01T00:00:00Z', Profile: 'foreground', Budget: {}}, Operation: {ID: 'operation', WorkflowID: 'workflow', Kind: 'chat', WorkloadProfile: 'foreground', AttemptLimit: 1, PayloadVersion: 1, ParentOperationID: ''}};
  await call('Journal.PrepareOperation', handle.handle, 'thread', operation);
  await assert.rejects(call('Journal.PrepareOperation', handle.handle, 'thread', {...operation, RequestHash: 'other'}), /conflict/);
  await assert.rejects(call('Journal.PrepareAttempt', handle.handle, 'thread', {OperationID: 'absent', AttemptID: 'attempt', WorkflowID: 'workflow', Ordinal: 1}), /operation/);
  await call('Journal.PrepareAttempt', handle.handle, 'thread', {OperationID: 'operation', AttemptID: 'attempt', WorkflowID: 'workflow', Ordinal: 1, At: '2026-01-01T00:00:00Z', RequestHash: 'request'});
  await call('Journal.CompleteAttempt', handle.handle, 'thread', {OperationID: 'operation', AttemptID: 'attempt', At: '2026-01-01T00:00:01Z', Outcome: 'succeeded', Failure: {}});
  await call('Journal.CompleteOperation', handle.handle, 'thread', {OperationID: 'operation', At: '2026-01-01T00:00:01Z', Outcome: 'succeeded', Failure: {}});
  await call('Journal.CompleteWorkflow', handle.handle, 'thread', {WorkflowID: 'workflow', At: '2026-01-01T00:00:01Z', Outcome: 'succeeded'});
  assert.equal((await call('Journal.Prune', handle.handle, '2026-02-01T00:00:00Z'))[0], 1);
  await call('Journal.PrepareOperation', handle.handle, 'thread', operation);
  await call('Journal.Close', handle.handle);
  await assert.rejects(call('Journal.Prune', handle.handle, '2026-02-01T00:00:00Z'), error => error.code === 'resource_unavailable');
  const [replacement] = await call('NewInferenceJournalRuntime', 'workspace');
  const [reconciled] = await call('Journal.ReconcileOrphans', replacement.handle, '2026-02-01T00:00:00Z');
  assert.equal(reconciled[0].OperationID, 'operation');
  assert.equal(reconciled[0].Outcome, 'blocked');
  assert.deepEqual((await call('Journal.ReconcileOrphans', replacement.handle, '2026-02-01T00:00:00Z'))[0], []);
  provider.shutdown();
});

test('independent turn state fences controls, driver identity and held message bytes', {skip: !entry}, async () => {
  const {createSessionProvider} = await import(pathToFileURL(entry));
  const provider = createSessionProvider(); provider.initialize(); provider.activate();
  const call = async (method, ...args) => (await provider.invokeService({service: 'session.domain', method, params: {args}, caller: 'owner'})).values;
  await call('CreateWithMetadata', 'thread', '/synthetic');
  const [control] = await call('ChangeControl', 'thread', 'manager', 'active', 0);
  await call('AppendControlledHistoryRecord', 'thread', {role: 'assistant', content: 'allowed'}, control);
  await call('ChangeControl', 'thread', 'manager', 'paused', 1);
  await assert.rejects(call('AppendControlledHistoryRecord', 'thread', {role: 'assistant', content: 'rejected'}, control), error => error.code === 'control_changed');
  assert.equal((await call('LoadHistoryRecords', 'thread', true))[0].length, 1);
  const binding = {contract_version: 1, driver_id: 'custom', driver_version: '1', profile: 'test', provider_id: 'independent'};
  await call('BindDriver', 'thread', binding);
  await assert.rejects(call('BindDriver', 'thread', {...binding, driver_id: 'other'}), /binding conflict/);
  const held = {ID: 'input-one', SessionID: 'thread', MessageJSON: 'eyJ0ZXh0IjoiYSJ9', RuntimeJSON: 'e30=', Origin: 'queue', Position: 0, DeliveryUnconfirmed: false};
  await call('AcceptHeldUserWork', 'thread', held);
  await assert.rejects(call('AppendAcceptedUserHistoryRecord', 'thread', {role: 'user', content: 'changed', client_id: held.ID}, {...held, MessageJSON: 'e30='}), /held input changed/);
  assert.equal((await call('LoadHeldUserWork', 'thread'))[0].length, 1);
  await call('AppendAcceptedUserHistoryRecord', 'thread', {role: 'user', content: 'accepted', client_id: held.ID}, held);
  assert.equal((await call('LoadHeldUserWork', 'thread'))[0].length, 0);
  assert.equal((await call('HasHeldUserWorkReceipt', 'thread', held.ID))[0], true);
  await call('ReplaceHeldUserWork', 'thread', []);
  assert.equal((await call('HasHeldUserWorkReceipt', 'thread', held.ID))[0], true);
  await assert.rejects(call('AcceptHeldUserWork', 'thread', held), error => error.code === 'held_work_settled');
  await assert.rejects(call('AppendAcceptedUserHistoryRecord', 'thread', {role: 'user', content: 'duplicate', client_id: held.ID}, held), error => error.code === 'held_work_settled');
  provider.shutdown();
});

test('independent provider checkpoints retain physical history and concurrent tail atomically', {skip: !entry}, async () => {
  const {createSessionProvider} = await import(pathToFileURL(entry));
  const provider = createSessionProvider(); provider.initialize(); provider.activate();
  const call = async (method, ...args) => (await provider.invokeService({service:'session.domain',method,params:{args},caller:'owner'})).values;
  await call('CreateInitialized', {id:'checkpoint',cwd:'/synthetic'}, [{role:'user',content:'original'}, {role:'assistant',content:'concurrent tail'}]);
  await assert.rejects(call('RewriteHistoryRecordsAtBaseline','checkpoint',[],3), /baseline/);
  await assert.rejects(call('RewriteHistoryRecordsAtBaseline','checkpoint',[{role:'user',content:42}],1), /history record/);
  assert.equal((await call('LatestHistoryCheckpoint','checkpoint'))[1], false);
  await call('RewriteHistoryRecordsAtBaseline','checkpoint',[{role:'user',content:'replacement'}],1);
  assert.deepEqual((await call('LoadHistoryRecords','checkpoint',true))[0].map(record => record.content), ['original','concurrent tail','replacement']);
  const [snapshot] = await call('LoadProviderHistorySnapshot','checkpoint');
  assert.equal(snapshot.HeadSeq,3);
  assert.deepEqual(snapshot.Records.map(record => record.seq),[3,2]);
  await call('AppendHistoryRecord','checkpoint',{role:'assistant',content:'after checkpoint'});
  assert.deepEqual((await call('LoadProviderHistorySnapshot','checkpoint'))[0].Records.map(record => record.content), ['replacement','concurrent tail','after checkpoint']);
  provider.shutdown();
});

test('independent request checkpoints are detached and indexing retains the original summary', {skip: !entry}, async () => {
  const {createSessionProvider} = await import(pathToFileURL(entry));
  const provider = createSessionProvider(); provider.initialize(); provider.activate();
  const call = async (method, ...args) => (await provider.invokeService({service:'session.domain',method,params:{args},caller:'owner'})).values;
  await assert.rejects(call('LoadRequestContextCheckpoint','missing'), error => error.code === 'session_not_found');
  await call('CreateWithMetadata','context','/synthetic');
  assert.equal((await call('LoadRequestContextCheckpoint','context'))[0],null);
  const checkpoint = {version:1,blocks:[{content:'retained'}]};
  await call('SaveRequestContextCheckpoint','context',checkpoint);
  checkpoint.blocks[0].content = 'mutated';
  assert.equal((await call('LoadRequestContextCheckpoint','context'))[0].blocks[0].content,'retained');
  await call('UpdateIndex','context',2,'original summary');
  await call('UpdateIndex','context',4,'later summary');
  const [metadata] = await call('Find','context');
  assert.equal(metadata.entries,4); assert.equal(metadata.summary,'original summary');
  await call('Delete','context');
  await call('CreateWithMetadata','context','/synthetic');
  assert.equal((await call('LoadRequestContextCheckpoint','context'))[0],null);
  provider.shutdown();
});
