import { strict as assert } from "node:assert";
import { applyModelUsage, readModelUsage } from "./usage.js";
import type { SessionDocument, State } from "./state.js";
const state = { run_id: "run", round: 1 } as State;
const doc = { tasks: [{ id: "run", usage: { input_tokens: 100, output_tokens: 50 } }, { id: "run:model:1" }] } as SessionDocument;
let calls = 0;
const receipt = { operation_id: "op", submission_id: "sub", provider: "provider", model: "model", outcome: "failed", cost_state: "known", usage: { input_tokens: 13, output_tokens: 7, cache_read_tokens: 4 } };
const source = { async modelReceipts(id: string) { assert.equal(id, "run:model:1"); calls++; return { status: "complete" as const, receipts: [receipt, receipt] }; } };
applyModelUsage(doc, state, await readModelUsage(source, state));
applyModelUsage(doc, state, await readModelUsage(source, state));
assert.equal(calls, 2);
assert.deepEqual(doc.tasks[0].usage, { input_tokens: 113, output_tokens: 57, cache_creation_tokens: 0, cache_read_tokens: 4 });
applyModelUsage(doc, state, { status: "unavailable", receipts: [] });
assert.equal(doc.tasks[0].usage?.input_tokens, 113);
assert.equal(doc.tasks[0].usage_status, "incomplete");
applyModelUsage(doc,state,{status:"incomplete",receipts:[{...receipt,usage:undefined}]});
assert.equal(doc.tasks[0].usage?.input_tokens,113);
applyModelUsage(doc,state,{status:"complete",receipts:[receipt]});
assert.equal(doc.tasks[0].usage?.input_tokens,113);
assert.throws(() => applyModelUsage(doc, state, { status: "complete", receipts: [{ ...receipt, operation_id: "forged" }] }), /identity/);
const overflow = { tasks: [{ id: "run", usage: { input_tokens: Number.MAX_SAFE_INTEGER, output_tokens: 0 } }, { id: "run:model:1" }] } as SessionDocument;
assert.throws(() => applyModelUsage(overflow, state, { status: "complete", receipts: [receipt] }), /aggregate/);
console.log("authoritative usage lookup, duplicate projection, failed operation and retained historical total passed");
