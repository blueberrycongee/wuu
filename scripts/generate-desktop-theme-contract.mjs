#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));
const contractPath = resolve(repoRoot, "config/desktop-theme-contract.json");
const checkOnly = process.argv.includes("--check");
const contract = JSON.parse(readFileSync(contractPath, "utf8"));

validateContract(contract);

const tokenNames = contract.tokens.map((token) => token.name);
const syntaxNames = contract.syntax;
const iconNames = contract.icons;
const legacyAliases = Object.fromEntries(
  contract.tokens.filter((token) => token.legacy).map((token) => [token.name, token.aliasFor]),
);
const outputs = new Map([
  [resolve(repoRoot, "internal/plugin/theme_contract_generated.go"), renderGo(tokenNames, syntaxNames, iconNames)],
  [resolve(repoRoot, "packages/plugin-sdk/src/theme-contract.generated.ts"), renderTypeScript(tokenNames, syntaxNames, iconNames, legacyAliases)],
  [resolve(repoRoot, "desktop/src/shared/themeContract.generated.ts"), renderTypeScript(tokenNames, syntaxNames, iconNames, legacyAliases)],
]);

let stale = false;
for (const [path, content] of outputs) {
  if (readOptional(path) === content) continue;
  stale = true;
  if (checkOnly) {
    console.error(`${relative(repoRoot, path)} is stale; run node scripts/generate-desktop-theme-contract.mjs`);
  } else {
    writeFileSync(path, content);
    console.log(`generated ${relative(repoRoot, path)}`);
  }
}

if (checkOnly && stale) process.exit(1);
if (checkOnly) console.log("desktop theme contract is current");

function validateContract(value) {
  if (!value || value.schemaVersion !== 1 || !Array.isArray(value.tokens) || !Array.isArray(value.syntax) || !Array.isArray(value.icons)) {
    fail("desktop theme contract must use schemaVersion 1 with tokens, syntax, and icons arrays");
  }
  const tokenPattern = /^--wuu-[a-z0-9-]+$/;
  const syntaxPattern = /^--(?:wuu-syntax|hljs)-[a-z0-9-]+$/;
  const categories = new Set(["color", "typography", "spacing", "density", "radius", "border", "elevation", "motion", "content"]);
  const seen = new Set();
  for (const [index, token] of value.tokens.entries()) {
    if (!token || typeof token.name !== "string" || !tokenPattern.test(token.name)) {
      fail(`tokens[${index}].name is invalid`);
    }
    if (!categories.has(token.category)) fail(`tokens[${index}].category is invalid`);
    if (seen.has(token.name)) fail(`duplicate theme token ${token.name}`);
    seen.add(token.name);
  }
  const tokenNames = new Set(value.tokens.map((token) => token.name));
  for (const [index, token] of value.tokens.entries()) {
    if (token.legacy && (typeof token.aliasFor !== "string" || !tokenNames.has(token.aliasFor))) {
      fail(`tokens[${index}].aliasFor must reference a public token`);
    }
    if (!token.legacy && token.aliasFor !== undefined) {
      fail(`tokens[${index}].aliasFor is only valid for legacy tokens`);
    }
  }
  for (const [index, name] of value.syntax.entries()) {
    if (typeof name !== "string" || !syntaxPattern.test(name)) fail(`syntax[${index}] is invalid`);
    if (seen.has(name)) fail(`duplicate theme token ${name}`);
    seen.add(name);
  }
  const iconPattern = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
  const seenIcons = new Set();
  for (const [index, name] of value.icons.entries()) {
    if (typeof name !== "string" || !iconPattern.test(name)) fail(`icons[${index}] is invalid`);
    if (seenIcons.has(name)) fail(`duplicate icon name ${name}`);
    seenIcons.add(name);
  }
}

function renderGo(tokens, syntax, icons) {
  const entries = (names) => {
    const quoted = names.map((name) => JSON.stringify(name));
    const width = Math.max(...quoted.map((name) => name.length));
    return quoted.map((name) => `\t${name}:${" ".repeat(width - name.length + 1)}{},`).join("\n");
  };
  return `// Code generated by scripts/generate-desktop-theme-contract.mjs; DO NOT EDIT.\n\npackage plugin\n\nvar allowedThemeTokens = map[string]struct{}{\n${entries(tokens)}\n}\n\nvar allowedSyntaxTokens = map[string]struct{}{\n${entries(syntax)}\n}\n\nvar allowedIconNames = map[string]struct{}{\n${entries(icons)}\n}\n`;
}

function renderTypeScript(tokens, syntax, icons, aliases) {
  const renderArray = (name, names) => `export const ${name} = [\n${names.map((value) => `  ${JSON.stringify(value)},`).join("\n")}\n] as const;`;
  const aliasEntries = Object.entries(aliases).map(([legacy, current]) => `  ${JSON.stringify(legacy)}: ${JSON.stringify(current)},`).join("\n");
  return `// Code generated by scripts/generate-desktop-theme-contract.mjs; DO NOT EDIT.\n\n${renderArray("PUBLIC_THEME_TOKEN_NAMES", tokens)}\n\nexport type PublicThemeTokenName = (typeof PUBLIC_THEME_TOKEN_NAMES)[number];\n\n${renderArray("PUBLIC_SYNTAX_TOKEN_NAMES", syntax)}\n\nexport type PublicSyntaxTokenName = (typeof PUBLIC_SYNTAX_TOKEN_NAMES)[number];\n\n${renderArray("PUBLIC_ICON_NAMES", icons)}\n\nexport type PublicIconName = (typeof PUBLIC_ICON_NAMES)[number];\n\nexport const LEGACY_THEME_TOKEN_ALIASES = {\n${aliasEntries}\n} as const satisfies Readonly<Partial<Record<PublicThemeTokenName, PublicThemeTokenName>>>;\n\nconst PUBLIC_THEME_TOKEN_SET: ReadonlySet<string> = new Set(PUBLIC_THEME_TOKEN_NAMES);\nconst PUBLIC_SYNTAX_TOKEN_SET: ReadonlySet<string> = new Set(PUBLIC_SYNTAX_TOKEN_NAMES);\nconst PUBLIC_ICON_NAME_SET: ReadonlySet<string> = new Set(PUBLIC_ICON_NAMES);\n\nexport function isPublicThemeTokenName(value: string): value is PublicThemeTokenName {\n  return PUBLIC_THEME_TOKEN_SET.has(value);\n}\n\nexport function isPublicSyntaxTokenName(value: string): value is PublicSyntaxTokenName {\n  return PUBLIC_SYNTAX_TOKEN_SET.has(value);\n}\n\nexport function isPublicIconName(value: string): value is PublicIconName {\n  return PUBLIC_ICON_NAME_SET.has(value);\n}\n\nexport function canonicalThemeTokenName(value: PublicThemeTokenName): PublicThemeTokenName {\n  return LEGACY_THEME_TOKEN_ALIASES[value as keyof typeof LEGACY_THEME_TOKEN_ALIASES] ?? value;\n}\n`;
}

function readOptional(path) {
  try {
    return readFileSync(path, "utf8");
  } catch (error) {
    if (error?.code === "ENOENT") return undefined;
    throw error;
  }
}

function fail(message) {
  console.error(message);
  process.exit(1);
}
