import { createRequire } from "node:module";
import { readdir, readFile, mkdir, writeFile, rename, rm } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(root, "plugins/package.json"));
const { build } = require("esbuild");
const args = process.argv.slice(2);
const check = args.includes("--check");
const selected = args.find((arg) => arg.startsWith("--plugin="))?.slice("--plugin=".length);
if (args.some((arg) => arg !== "--check" && !arg.startsWith("--plugin="))) {
  throw new Error("usage: node scripts/build-bundled-plugins.mjs [--plugin=<id>] [--check]");
}
const pluginsRoot = join(root, "plugins");
const pluginIDs = (await readdir(pluginsRoot, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory() && !entry.name.startsWith(".") && entry.name !== "node_modules")
  .map((entry) => entry.name).sort();
if (selected && !pluginIDs.includes(selected)) throw new Error(`unknown bundled plugin: ${selected}`);

for (const id of selected ? [selected] : pluginIDs) {
  const packageRoot = join(root, "internal/plugin/bundled", id);
  const manifest = JSON.parse(await readFile(join(packageRoot, "plugin.json"), "utf8"));
  const result = await build({
    absWorkingDir: root,
    stdin: {
      contents: `import plugin from "./src/index.ts";
import { runJSONLRuntime } from "@wuu/plugin-sdk";
const [major, minor] = process.versions.node.split(".").map(Number);
if (major < 22 || (major === 22 && minor < 7)) {
  throw new Error("Wuu plugins require Node.js 22.7+ or the Wuu desktop runtime.");
}
await runJSONLRuntime(plugin, { input: process.stdin, output: process.stdout });
`,
      resolveDir: join(pluginsRoot, id),
      sourcefile: `plugins/${id}/runtime-entry.ts`,
      loader: "ts",
    },
    alias: { "@wuu/plugin-sdk": join(root, "packages/plugin-sdk/src/index.ts") },
    bundle: true,
    platform: "node",
    target: "node22.7",
    format: "esm",
    write: false,
    legalComments: "inline",
    banner: { js: "// Generated by scripts/build-bundled-plugins.mjs. Do not edit." },
  });
  const output = result.outputFiles[0].contents;
  const runtime = join(packageRoot, "runtime.mjs");
  if (check) {
    let current;
    try { current = await readFile(runtime); } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    if (!current?.equals(output)) throw new Error(`${id} runtime is stale; run npm --prefix plugins run build`);
    continue;
  }
  await writeChanged(runtime, output);

  // The canonical package stays beside the embedded assets. A generated local
  // manifest and dist copy let the ordinary public directory watcher rebuild
  // this same package without duplicating its author-maintained metadata.
  const developmentRoot = join(pluginsRoot, id);
  await copyPackage(packageRoot, join(developmentRoot, "dist"));
  manifest.runtime.args = ["dist/runtime.mjs"];
  if (manifest.skills) {
    const skills = Array.isArray(manifest.skills) ? manifest.skills : [manifest.skills];
    manifest.skills = skills.map((path) => `./dist/${path.replace(/^\.\//, "")}`);
  }
  if (manifest.desktop) manifest.desktop.entry = `dist/${manifest.desktop.entry}`;
  for (const command of manifest.contributes?.commands ?? []) {
    if (command.prompt) command.prompt = `./dist/${command.prompt.replace(/^\.\//, "")}`;
  }
  await writeChanged(join(developmentRoot, "plugin.json"), JSON.stringify(manifest, null, 2) + "\n");
}
console.log(`${check ? "verified" : "built"} ${selected ? 1 : pluginIDs.length} TypeScript plugin runtime(s)`);

async function writeChanged(path, content) {
  const data = Buffer.from(content);
  try { if ((await readFile(path)).equals(data)) return; } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  await mkdir(dirname(path), { recursive: true });
  const temporary = `${path}.${process.pid}.tmp`;
  await writeFile(temporary, data);
  await rename(temporary, path);
}

async function copyPackage(source, destination) {
  const entries = await readdir(source, { withFileTypes: true });
  await mkdir(destination, { recursive: true });
  const names = new Set(entries.map((entry) => entry.name));
  for (const name of await readdir(destination)) {
    if (!names.has(name)) await rm(join(destination, name), { recursive: true, force: true });
  }
  for (const entry of entries) {
    const path = join(source, entry.name);
    const target = join(destination, entry.name);
    if (entry.isDirectory()) await copyPackage(path, target);
    else if (entry.isFile()) await writeChanged(target, await readFile(path));
    else throw new Error(`unsupported package asset: ${path}`);
  }
}
