import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const {build}=createRequire(resolve(root,'plugins/package.json'))('esbuild');
export async function buildPersonalDesktop(check=false) {
  const result=await build({absWorkingDir:root,entryPoints:[resolve(root,'plugins/personal/ui/desktop.js')],bundle:true,write:false,format:'iife',globalName:'personalDesktop',platform:'browser',target:'es2022',loader:{'.css':'text'},banner:{js:'// Generated by scripts/build-personal-desktop.mjs. Edit plugins/personal/ui/desktop.js.'}});
  const target=resolve(root,'internal/plugin/bundled/personal/desktop.js'), output=Buffer.from(result.outputFiles[0].text+'\nexport async function activate(api) { return personalDesktop.activate(api); }\n');
  if(check){if(!Buffer.from(await readFile(target)).equals(output))throw new Error('Personal desktop entry is stale');}
  else await writeFile(target,output);
}
if(process.argv[1]===fileURLToPath(import.meta.url))await buildPersonalDesktop(process.argv.includes('--check'));
